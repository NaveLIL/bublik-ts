import { Config } from '../../config';

/** Empty/missing OWNER_ID is deliberately fail-closed: nobody receives immunity. */
export function isConfiguredEconomyOwner(
  userId: string,
  configuredOwnerId: string | null | undefined = Config.ownerId,
): boolean {
  const ownerId = configuredOwnerId?.trim();
  return Boolean(ownerId) && userId === ownerId;
}

function pick(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

